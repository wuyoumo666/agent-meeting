export function findPersonaPreset(id?: string): PersonaPreset | undefined {
  if (!id || id === 'custom' || id === 'none') return undefined
  return PERSONA_PRESETS.find((preset) => preset.id === id)
}

export function personaDisplayLabel(agent: Pick<Agent, 'chatPreset' | 'chatPersona'>): string {
  const preset = findPersonaPreset(agent.chatPreset)
  if (preset) return preset.badge
  if (agent.chatPreset === 'custom' || agent.chatPersona?.trim()) return '自定义人设'
  return ''
}

export function buildPureChatPersonaSection(agent: Agent, roomAgents: Agent[]): string {
  const preset = findPersonaPreset(agent.chatPreset)
  const customBody = agent.chatPersona?.trim()
  const roomCast = roomAgents.length > 1
    ? `\n\n【群聊里其他同伴的性格标签（自然称呼和互动即可，无需套固定场景）】\n${roomAgents.map((member) => {
      const p = findPersonaPreset(member.chatPreset)
      return `- 「${member.name}」：${p ? `${p.name}性格（${p.aliases}）` : '普通朋友'}`
    }).join('\n')}`
    : ''

  if (preset) {
    return `${APARTMENT_SHARED_PREFIX}\n\n【你的性格与说话设定】\n${customBody || preset.prompt}\n\n${APARTMENT_RELATIONS}${roomCast}`
  }
  if (customBody) {
    return `【你的聊天性格设定】\n${customBody}`
  }
  return `你现在叫「${agent.name}」，正在轻松日常聊天。请保持自然、真诚、口语化的对话风格，不要套用工作报告格式或写场景旁白。`
}
